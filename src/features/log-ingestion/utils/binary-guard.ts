const MAGIC_SIGNATURES: readonly (readonly number[])[] = [
  [0x7f, 0x45, 0x4c, 0x46],
  [0x4d, 0x5a],
  [0xfe, 0xed, 0xfa, 0xce],
  [0xfe, 0xed, 0xfa, 0xcf],
  [0xce, 0xfa, 0xed, 0xfe],
  [0xcf, 0xfa, 0xed, 0xfe],
  [0xca, 0xfe, 0xba, 0xbe],
  [0x50, 0x4b, 0x03, 0x04],
  [0x50, 0x4b, 0x05, 0x06],
  [0x1f, 0x8b],
  [0x37, 0x7a, 0xbc, 0xaf, 0x27, 0x1c],
  [0x25, 0x50, 0x44, 0x46],
];

export const isBinaryPayload = (chunk: Uint8Array): boolean => {
  for (let i = 0; i < chunk.length; i++) {
    if (chunk[i] === 0) {
      return true;
    }
  }

  for (const signature of MAGIC_SIGNATURES) {
    if (chunk.length < signature.length) {
      continue;
    }

    const matches = signature.every((byte, index) => chunk[index] === byte);

    if (matches) {
      return true;
    }
  }

  return false;
};
